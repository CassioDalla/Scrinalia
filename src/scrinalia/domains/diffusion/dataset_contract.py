def contract_directory() -> str:
    """The committed directory of this contract version (``v1``)."""
    return f"v{DATASET_SCHEMA_VERSION.split('.')[0]}"


class DatasetLicense(BaseModel):
    """
    The **data** license, which is not the software license.

    The software is AGPL-3.0-only with an attribution term (ADR 0006); that says nothing about the
    records, and an institution may diffuse a collection under CC BY while the software stays AGPL.
    The two are separate on purpose, and the manifest carries both.

    ``attribution`` is the TASL line (Title, Author, Source, License) a CC BY reuse must display. It is
    required for the licenses that demand it, and optional for CC0, which waives attribution.
    """

    model_config = ConfigDict(extra="forbid")

    id: DatasetLicenseId
    name: str = Field(min_length=1, max_length=200)
    url: HttpUrl | None = None
    attribution: str | None = Field(default=None, max_length=2000)

    @model_validator(mode="after")
    def _the_license_states_its_terms(self) -> DatasetLicense:
        """A named license carries its terms; an unnamed one has to publish them."""
        if self.id == "custom" and (self.url is None or not self.attribution):
            raise ValueError("a custom data license needs a URL and an attribution line")
        if self.id in ("CC-BY-4.0", "CC-BY-SA-4.0") and not self.attribution:
            raise ValueError("CC BY and CC BY-SA require the attribution line (TASL)")
        return self


class DatasetInstitution(BaseModel):
    """Who publishes the dataset, and how a consumer reaches them."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=1, max_length=200)
    contact_email: str | None = Field(default=None, max_length=254)
    url: HttpUrl | None = None


class DatasetArtifact(BaseModel):
    """One file of the package, with the hash a consumer verifies before ingesting it."""

    model_config = ConfigDict(extra="forbid")

    format: Literal["json", "ndjson", "csv"]
    path: str = Field(min_length=1, max_length=200)
    bytes: int = Field(ge=0)
    sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    records: int = Field(ge=0)


class DatasetSoftware(BaseModel):
    """The software that wrote the package, and where its source and license are."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=1, max_length=100)
    version: str = Field(min_length=1, max_length=50)
    license: str = Field(min_length=1, max_length=50)
    license_url: HttpUrl
    source_url: HttpUrl


class DatasetManifest(BaseModel):
    """
    ``manifest.json``: what the package is, what it contains and what changed since the last one.

    ``snapshot_id`` is the content identity: the writer derives it from the ordered records, **not**
    from ``generated_at``, so two runs over the same covered set share it and a consumer can tell
    "nothing changed" without downloading the files again. ``previous_snapshot_id`` and ``removals``
    are what let a custom site delete what left the published set; the dataset keeps no tombstone of
    its own, the coverage is the truth.

    The manifest is a document the installation writes, so ``extra="forbid"`` is safe: an unknown key
    is a writer bug, not a consumer's extension.
    """

    model_config = ConfigDict(extra="forbid")

    schema_version: DatasetSchemaVersion
    snapshot_id: str = Field(pattern=r"^[0-9a-f]{64}$")
    #: ``None`` on the first snapshot, or when the destination changed.
    previous_snapshot_id: str | None = Field(default=None, pattern=r"^[0-9a-f]{64}$")
    generated_at: AwareDatetime
    record_count: int = Field(ge=0)
    artifacts: list[DatasetArtifact] = Field(min_length=1)
    #: Description ids that were in the previous snapshot and are not covered now. Empty when there
    #: is no previous snapshot to compare against.
    removals: list[str]
    license: DatasetLicense
    institution: DatasetInstitution
    software: DatasetSoftware
    #: The live read of the same channel, when the installation publishes one; the snapshot and the
    #: API are the two paths the diffusion guide documents.
    api_url: HttpUrl | None
    openapi_url: HttpUrl | None
    field_map: str = Field(default="field-map.json", min_length=1, max_length=200)
    readme: str = Field(default="README.md", min_length=1, max_length=200)


