def field_map_document() -> dict[str, object]:
    """The published crosswalk: version, conventions and one entry per record field."""
    return {
        "schema_version": DATASET_SCHEMA_VERSION,
        "record_schema": "documents.schema.json",
        "record_model": "PublicDocumentSummary",
        "conventions": {
            "csv": "RFC 4180, comma delimiter, UTF-8 without BOM, one header row.",
            "dates": "document_date is an ISO 8601 date; date_expression keeps the source spelling.",
            "ids": "description_id is opaque and stable within one installation; do not parse it.",
            "language": "language_name is the label the archive declared, not a normalized BCP 47 tag.",
            "multivalue": "arrays in JSON and NDJSON; the same JSON array encoded in one CSV cell.",
            "null": "an absent value is null in JSON and an empty cell in CSV.",
        },
        "fields": [
            {
                "name": field.name,
                "kind": field.kind.value,
                "isad_g": field.isad_g,
                "cardinality": field.cardinality,
                "description": field.description,
            }
            for field in DATASET_FIELDS
        ],
    }


def documents_schema() -> dict[str, object]:
    """JSON Schema of one exported record, generated from the public projection."""
    return PublicDocumentSummary.model_json_schema()


def manifest_schema() -> dict[str, object]:
    """JSON Schema of ``manifest.json``, generated from :class:`DatasetManifest`."""
    return DatasetManifest.model_json_schema()


def contract_documents() -> dict[str, dict[str, object]]:
    """
    Every committed artifact, keyed by file name.

    The dump command and the staleness test both read this function, so the files cannot be
    regenerated with a different shape than the one the test compares against.
    """
    return {
        "documents.schema.json": documents_schema(),
        "manifest.schema.json": manifest_schema(),
        "field-map.json": field_map_document(),
    }


def assert_schema_version_is_the_literal() -> None:
    """
    The constant and the manifest's ``Literal`` are the same version.

    ``Literal`` cannot take a constant, so the two declarations exist; this function is the one place
    that reads them together, and the test calls it. Without it a bump of the constant could leave the
    manifest declaring the old version and the generated schema would agree with the wrong one.
    """
    declared = get_args(DatasetManifest.model_fields["schema_version"].annotation)
    if declared != (DATASET_SCHEMA_VERSION,):
        raise AssertionError(f"the manifest declares {declared}, the contract declares {DATASET_SCHEMA_VERSION!r}")
