/**
 * The copy of the two exclusion screens and their shared vocabulary (ADR 0020 §7). The section is
 * merged into `pages` by `i18n/pt.ts` and `i18n/en.ts`; keeping it in its own module is what lets the
 * screens be extracted without touching the central catalogue.
 *
 * The three sections follow the three routes: `blockedSpellings` (`/assuntos/grafias`) vetoes a
 * *spelling*, `subjectExclusions` (`/assuntos/excecoes`) decides that a term is **not a subject**,
 * and `nerExclusions` (`/entidades/excecoes`) decides that a term is a **subject and not a name**.
 * The sentence that keeps the first two apart is not here: it is `spellings` in the central
 * catalogue, because the tags screen reads it too.
 *
 * `pt` is deliberately not `as const`: `en` is typed as its shape, so a literal type would demand
 * the Portuguese text in the English catalogue. Without it the keys are still fixed — a missing or
 * extra key is a `tsc` failure — which is the parity ADR 0020 §1 asks for.
 */

