"""Every field of the manual contract has a control on the form (#192).

The form is a screen, not a contract: nothing stops a field added to ``ManualIngestionRequest`` from
being absent from the JSX, and the API's ``extra="forbid"`` would never notice — the submit simply
never sends it and the address answers 201 with the value missing. That is the same silent-loss
shape the ``MANUAL_FIELDS`` pin closes on the server side, one layer up.

The check is textual, like the API body-shape gates (the SPA has no test runner of its own): the ISAD
catalogue names the record's fields, ``setValue("<name>")`` names the controls the form renders by
hand (title, level, parent, access points, source URL, image), and the two together must be the
contract minus the record's identity. A field the form deliberately does not ask — ``description_dates``,
which the dossier edits — says so in the catalogue with ``manualEntry: false``.
"""

from __future__ import annotations

import re
from pathlib import Path

from scrinalia.domains.ingestion.schemas import ManualIngestionRequest

REPO_ROOT = Path(__file__).resolve().parents[3]
ISAD = REPO_ROOT / "apps" / "curator" / "src" / "lib" / "isad.ts"
FORM = REPO_ROOT / "apps" / "curator" / "src" / "routes" / "NewDescriptionRoute.tsx"

#: One catalogue entry: ``field("name", "area", "control")``, with ``false`` when the form skips it.
FIELD = re.compile(r'^\s*field\("([a-z_]+)",\s*"[a-z]+",\s*"[a-z_]+"(?:,\s*(false))?\),$', re.M)

#: The controls the form binds by hand, outside the catalogue.
BOUND_CONTROL = re.compile(r'setValue\("([a-z_]+)"')


def _catalogue_fields() -> set[str]:
    """The catalogue's fields, minus the ones marked as not asked at creation."""
    return {name for name, not_asked in FIELD.findall(ISAD.read_text()) if not not_asked}


def test_every_contract_field_has_a_control_on_the_form() -> None:
    described = _catalogue_fields() | set(BOUND_CONTROL.findall(FORM.read_text()))
    contract = set(ManualIngestionRequest.model_fields) - {"description_id"}

    missing = sorted(contract - described)
    extra = sorted(described - contract)

    assert missing == [], f"o formulário não oferece: {missing}"
    assert extra == [], f"o formulário oferece campo que o contrato não tem: {extra}"


def test_the_two_fields_the_form_does_not_ask_say_so() -> None:
    """
    The identity is generated by the screen, and the description dates are the dossier's.

    Asserting both keeps the gate above from quietly widening: the day the form starts asking
    ``description_dates``, the catalogue drops its ``manualEntry: false`` and this test says so.
    """
    described = _catalogue_fields() | set(BOUND_CONTROL.findall(FORM.read_text()))

    assert "description_id" in ManualIngestionRequest.model_fields
    assert "description_id" not in described, "o id é gerado pela tela, não um controle"
    assert "description_dates" not in described, "o form não pergunta as datas da descrição"
